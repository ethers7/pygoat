@authentication_decorator
def csrf_lab_login(request):
    if request.method == 'GET':
        return render(request, 'mitre/csrf_lab_login.html')
    elif request.method == 'POST':
        password = request.POST.get('password')
        username = request.POST.get('username')
        # CWE-327: the lab account password is checked against the salted,
        # adaptive hash stored for that row (see check_lab_password) instead of
        # matching an unsalted MD5 digest in the query. A stored value no
        # configured hasher can identify (e.g. a legacy MD5 digest) is rejected,
        # so the login fails closed instead of using a broken algorithm.
        User = CSRF_user_tbl.objects.filter(username=username).first()
        if User is not None and check_lab_password(password, User.password):
            payload ={
                'username': username,
                'exp': datetime.datetime.utcnow() + datetime.timedelta(seconds=300),
                'iat': datetime.datetime.utcnow()
            }
            # Signing key comes from settings.CSRF_LAB_JWT_KEY (environment
            # supplied) - never a literal in this module.
            cookie = jwt.encode(payload, settings.CSRF_LAB_JWT_KEY, algorithm='HS256')
            response = redirect("/mitre/9/lab/transaction")
            # CWE-614: this JWT is the lab session. It is decoded server side in
            # csrf_transfer_monei/_api, so no script needs it (HttpOnly) and it
            # must not ride along on cross-site requests (SameSite=Lax). Secure
            # follows settings.LAB_COOKIE_SECURE: docker-compose serves PyGoat
            # over plain HTTP, where a browser would drop a Secure cookie.
            response.set_cookie(
                'auth_cookiee', cookie,
                httponly=True, samesite='Lax',
                secure=settings.LAB_COOKIE_SECURE)
            return response
        else :
            return redirect('/mitre/9/lab/login')

@authentication_decorator
def csrf_transfer_monei(request):
    if request.method == 'GET':
        try:
            cookie = request.COOKIES['auth_cookiee']
            payload = jwt.decode(cookie, settings.CSRF_LAB_JWT_KEY, algorithms=['HS256'])
            username = payload['username']
            User = CSRF_user_tbl.objects.filter(username=username)
            if not User:
                redirect('/mitre/9/lab/login')
            return render(request, 'mitre/csrf_dashboard.html', {'balance': User[0].balance})
        except:
            return redirect('/mitre/9/lab/login')

def csrf_transfer_monei_api(request,recipent,amount):
    if request.method == "GET":
        cookie = request.COOKIES['auth_cookiee']
        payload = jwt.decode(cookie, settings.CSRF_LAB_JWT_KEY, algorithms=['HS256'])
        username = payload['username']
        User = CSRF_user_tbl.objects.filter(username=username)
        if not User:
            return redirect('/mitre/9/lab/login')
        if int(amount) > 0:
            if int(amount) <= User[0].balance:
                recipent = CSRF_user_tbl.objects.filter(username=recipent)
                if recipent:
                    recipent = recipent[0]
                    recipent.balance = recipent.balance + int(amount)
                    recipent.save()
                    User[0].balance = User[0].balance - int(amount)
                    User[0].save()
        return redirect('/mitre/9/lab/transaction') 
    else:
        return redirect ('/mitre/9/lab/transaction')


